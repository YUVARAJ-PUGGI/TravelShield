USE travelshield_db;

-- Educational examples only. These rows are not real insurance coverage,
-- guarantees, or promises of reimbursement.
CREATE TABLE IF NOT EXISTS plan_benefits (
  benefit_id INT NOT NULL AUTO_INCREMENT,
  plan_id INT NOT NULL,
  benefit_name VARCHAR(150) NOT NULL,
  benefit_category ENUM(
    'emergency_medical_treatment',
    'medical_evacuation_repatriation',
    'flight_cancellation_interruption',
    'travel_delay',
    'missed_connection',
    'lost_damaged_baggage',
    'delayed_baggage_essentials',
    'emergency_accommodation',
    'emergency_return_travel',
    'lost_travel_document_replacement'
  ) NOT NULL,
  description TEXT NOT NULL,
  benefit_limit DECIMAL(12,2) NULL,
  currency_code CHAR(3) NOT NULL,
  required_evidence JSON NOT NULL,
  exclusions_conditions TEXT NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP
    ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (benefit_id),
  UNIQUE KEY uq_plan_benefit_name (plan_id, benefit_name),
  KEY idx_plan_benefits_plan_active (plan_id, is_active),
  KEY idx_plan_benefits_category (benefit_category),
  CONSTRAINT fk_plan_benefits_plan
    FOREIGN KEY (plan_id) REFERENCES plans (plan_id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT chk_plan_benefits_limit
    CHECK (benefit_limit IS NULL OR benefit_limit >= 0),
  CONSTRAINT chk_plan_benefits_currency
    CHECK (CHAR_LENGTH(currency_code) = 3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

